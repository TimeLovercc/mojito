def ics_of(c: Clock, t: Lang) -> str:
    fmt = "%Y%m%dT%H%M%SZ"
    stamp = datetime.now(UTC).strftime(fmt)
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//demo//sam//EN"]
    for e in calendar_of(c, t):
        lines += ["BEGIN:VEVENT", f"UID:{e['uid']}@demo.invalid", f"DTSTAMP:{stamp}"]
        if e["all_day"]:
            lines += [f"DTSTART;VALUE=DATE:{e['start']:%Y%m%d}", f"DTEND;VALUE=DATE:{e['end']:%Y%m%d}"]
        else:
            lines += [f"DTSTART:{e['start'].astimezone(UTC).strftime(fmt)}", f"DTEND:{e['end'].astimezone(UTC).strftime(fmt)}"]
        lines.append(f"SUMMARY:{e['title']}")
        if e["location"] is not None:
            lines.append(f"LOCATION:{e['location']}")
        if e["rrule"] is not None:
            lines.append(f"RRULE:{e['rrule']}")
        lines.append("END:VEVENT")
    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n"


