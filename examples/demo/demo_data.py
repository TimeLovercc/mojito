def fcm_placeholder(out: Path) -> Path:
    """A service-account file the hub can load without a Firebase project: Android push stays off (the web app
    does not need it). Replace it with a real one to push to the Android app."""
    key = out / "fcm-placeholder.key"
    openssl("genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-out", str(key))
    path = out / "fcm-placeholder.json"
    write_private(path, json.dumps({"type": "service_account", "project_id": "demo-no-push", "private_key_id": "demo",
                                    "private_key": key.read_text(), "client_email": "demo-no-push",
                                    "token_uri": "https://oauth2.googleapis.com/token"}, indent=2))
    key.unlink()
    return path


