# ---------------------------------------------------------------- time and language

class Clock:
    """Day offsets from the story's today; times are wall-clock times in `tz`."""

    def __init__(self, day: date, tz: ZoneInfo):
        self.day, self.tz = day, tz

    def at(self, n: int, hm: str) -> datetime:
        h, m = hm.split(":")
        return datetime.combine(self.day + timedelta(days=n), time(int(h), int(m)), self.tz)

    def iso(self, n: int, hm: str) -> str:
        return self.at(n, hm).isoformat(timespec="seconds")

    def ymd(self, n: int) -> str:
        return (self.day + timedelta(days=n)).isoformat()


class Lang:
    """t(zh, en) picks the text of the chosen UI language (settings.language)."""

    def __init__(self, language: str):
        if language not in ("zh", "en"):
            raise SystemExit(f"--language must be zh or en, got {language!r}")
        self.language = language

    def __call__(self, zh: str, en: str) -> str:
        return zh if self.language == "zh" else en


def hm_plus(hm: str, minutes: int) -> str:
    h, m = hm.split(":")
    total = int(h) * 60 + int(m) + minutes
    if total >= 24 * 60:
        raise SystemExit(f"{hm} + {minutes} min passes midnight; pick an earlier --evening-at")
    return f"{total // 60:02d}:{total % 60:02d}"


def db_ts(dt: datetime) -> str:
    """The hub's stored format (db.ts): UTC ISO-8601, second precision."""
    return dt.astimezone(UTC).isoformat(timespec="seconds")


def sha7(text: str) -> str:
    return hashlib.sha1(text.encode()).hexdigest()[:7]


def slug_of(app_name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", app_name.lower()).strip("-")


