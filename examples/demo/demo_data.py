class Hub:
    def __init__(self, out: Path):
        self.url = meta(out)["hub"]
        self.token = {role: tok for tok, role in json.loads((out / "tokens.json").read_text()).items()}

    def call(self, role: str, method: str, path: str, body: dict | None):
        headers = {"Authorization": f"Bearer {self.token[role]}"}
        data = None
        if body is not None:
            headers["Content-Type"] = "application/json"
            data = json.dumps(body).encode()
        req = urllib.request.Request(self.url + path, data=data, method=method, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                text = resp.read().decode()
        except urllib.error.HTTPError as e:  # re-raised with the hub's detail
            raise RuntimeError(f"{method} {path} -> {e.code}: {e.read().decode()}") from e
        return None if text == "" else json.loads(text)


class NewRecords:
    """Records the hub writes while `load` talks to it, each tagged with its story time (backdate moves them)."""

    def __init__(self, db: sqlite3.Connection):
        self.db, self.tagged = db, []
        self.last = db.execute("SELECT COALESCE(MAX(rowid), 0) FROM records").fetchone()[0]

    def tag(self, at: datetime) -> None:
        rows = self.db.execute("SELECT rowid, id FROM records WHERE rowid > ? ORDER BY rowid", (self.last,)).fetchall()
        self.tagged += [[rid, db_ts(at)] for _, rid in rows]
        if rows:
            self.last = rows[-1][0]


def cmd_load(a) -> None:
    out = Path(a.out).resolve()
    m = meta(out)
    c, t, app = Clock(date.fromisoformat(m["day"]), ZoneInfo(m["timezone"])), Lang(m["language"]), m["app_name"]
    db = sqlite3.connect(f"file:{out / 'demo.db'}?mode=ro", uri=True)
    if db.execute("SELECT COUNT(*) FROM devices").fetchone()[0] != 0:
        raise SystemExit("a device is already registered: loading history now would push to it. Use reset instead.")
    if db.execute("SELECT COUNT(*) FROM cards").fetchone()[0] != 0:
        raise SystemExit("already loaded (cards exist). Use reset, or build a new instance.")
    hub, x, new = Hub(out), extras_of(c, t, app), NewRecords(db)
    done = {"load_start": db_ts(datetime.now(UTC) - timedelta(seconds=1)), "cards": [], "taste": [],
            "subscriptions": [], "feedback": []}

    # Sam set the lab watch list in chat a few days ago (the hub records the change)
    watch = next(s for s in hub.call("app", "GET", "/subscriptions", None)["subscriptions"] if s["id"] == "watch")
    hub.call("worker", "PUT", "/subscriptions/watch", {"at": watch["at"], "config": x["watch_config"]})
    new.tag(c.at(-4, "21:05"))

    for card in cards_of(c, t):
        body = {k: card[k] for k in ("origin", "kind", "project_id", "title", "summary", "body", "link", "dedupe_key")}
        done["cards"].append([hub.call("source:cards", "POST", "/cards", body)["id"], db_ts(card["at"])])
        new.tag(card["at"])

    for text, at in x["taste"]:
        done["taste"].append([hub.call("agent", "POST", "/taste", {"text": text})["id"], db_ts(at)])
        new.tag(at)

    for sub_id, result, at in x["subscription_results"]:
        hub.call("worker", "POST", f"/subscriptions/{sub_id}/result", {"result": result, "health": "ok"})
        done["subscriptions"].append([sub_id, db_ts(at)])
        new.tag(at)

    prev_plan = next(p["id"] for p in json.loads((out / "seed.json").read_text())["plans"] if p["status"] == "closed")
    r = x["review"]
    hub.call("worker", "PUT", f"/reviews/{prev_plan}", {k: r[k] for k in ("summary", "completed_item_ids", "missed_item_ids", "patterns")})
    hub.call("app", "POST", f"/reviews/{prev_plan}/finish", {"user_note": r["user_note"]})
    done["review"] = [prev_plan, db_ts(r["at"])]
    new.tag(r["at"])

    for pid, summary in x["summaries"].items():
        hub.call("worker", "PUT", f"/projects/{pid}/summary", {"summary": summary, "summary_evidence": x["summary_evidence"][pid]})
    done["summary_at"] = db_ts(x["summary_at"])
    for pid, snap in x["snapshots"].items():
        hub.call("worker", "PUT", f"/projects/{pid}/snapshot", snap)
    new.tag(x["summary_at"])

    # project cards: the worker copies overview.json / writes Claude's; Sam's own edit came through chat (agent) and
    # leaves a change record with an undo
    for pid, overview in x["overviews"].items():
        hub.call("agent" if overview["source"] == "me" else "worker", "PUT", f"/projects/{pid}/overview", overview)
        new.tag(datetime.fromisoformat(overview["checked_at"]))

    events = [{"at": c.iso(n, hm), "kind": "view", "name": "app_open", "detail": None} for n, hms in x["opens"].items() for hm in hms]
    hub.call("app", "POST", "/usage", {"events": events})

    for fb in feedback_history(c, t, app):
        context = {"screen": fb["screen"], "item_id": None, "project_id": None, "app_update_id": None}
        fid = hub.call("app", "POST", "/feedback", {"body": fb["body"], "attachment_ids": [], "context": context})["id"]
        new.tag(fb["at"])
        for status, ship_mode, summary, at in fb["steps"]:
            if status == "approve":
                hub.call("app", "POST", f"/feedback/{fid}/decision", {"action": "approve"})
            else:
                hub.call("maintainer", "PUT", f"/feedback/{fid}", {"status": status, "ship_mode": ship_mode, "summary": summary})
            new.tag(at)
        done["feedback"].append([fid, db_ts(fb["at"]), db_ts(fb["steps"][-1][3])])

    done["records"] = new.tagged
    db.close()
    (out / "loaded.json").write_text(json.dumps(done, ensure_ascii=False, indent=2))
    print(f"loaded {len(done['cards'])} cards, {len(done['feedback'])} feedback, {len(done['records'])} records; "
          "stop the hub, then run backdate")


def cmd_backdate(a) -> None:
    out = Path(a.out).resolve()
    done = json.loads((out / "loaded.json").read_text())
    start = done["load_start"]
    db = sqlite3.connect(out / "demo.db")
    with db:
        for cid, at in done["cards"]:
            db.execute("UPDATE cards SET at = ? WHERE id = ?", (at, cid))
        for tid, at in done["taste"]:
            db.execute("UPDATE taste_notes SET at = ? WHERE id = ?", (at, tid))
        for sid, at in done["subscriptions"]:
            db.execute("UPDATE subscriptions SET last_run_at = ? WHERE id = ?", (at, sid))
        db.execute("UPDATE reviews SET created_at = ? WHERE plan_id = ?", (done["review"][1], done["review"][0]))
        db.execute("UPDATE projects SET summary_at = ? WHERE summary_at >= ?", (done["summary_at"], start))
        for fid, at, updated in done["feedback"]:
            db.execute("UPDATE feedback SET at = ?, updated_at = ? WHERE id = ?", (at, updated, fid))
        for rid, at in done["records"]:
            db.execute("UPDATE records SET at = ? WHERE id = ?", (at, rid))
        left = db.execute("SELECT title FROM records WHERE at >= ?", (start,)).fetchall()
        if left:
            raise SystemExit(f"records written during load still carry load time (written by the hub on its own?): {left}")
    db.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    db.close()
    golden = out / "golden"
    if golden.exists():
        shutil.rmtree(golden)
    golden.mkdir()
    shutil.copy2(out / "demo.db", golden / "demo.db")
    shutil.copytree(out / "attachments", golden / "attachments")
    print(f"backdated; golden copy in {golden}")


def cmd_reset(a) -> None:
    out = Path(a.out).resolve()
    for suffix in ("-wal", "-shm"):
        (out / f"demo.db{suffix}").unlink(missing_ok=True)
    shutil.copy2(out / "golden" / "demo.db", out / "demo.db")
    shutil.rmtree(out / "attachments")
    shutil.copytree(out / "golden" / "attachments", out / "attachments")
    (out / "attachments").chmod(0o700)
    print("reset to golden; start the hub and reopen the app")


